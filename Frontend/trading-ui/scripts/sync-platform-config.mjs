#!/usr/bin/env node
/**
 * Generates src/app/core/config/platform-config.generated.ts from Config/application.yaml,
 * the shared port settings for every service. Runs before start, build, watch and test.
 *
 *   node scripts/sync-platform-config.mjs            regenerate the file
 *   node scripts/sync-platform-config.mjs --serve    regenerate, then `ng serve` on frontend.port
 */
import { spawn } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse } from 'yaml';

const appRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const configPath = process.env.PLATFORM_CONFIG_PATH || resolve(appRoot, '..', '..', 'Config', 'application.yaml');
const outPath = resolve(appRoot, 'src', 'app', 'core', 'config', 'platform-config.generated.ts');

export function loadPlatformUrls(path = configPath) {
  if (!existsSync(path)) {
    throw new Error(`Platform config not found at ${path} (set PLATFORM_CONFIG_PATH or restore Config/application.yaml)`);
  }
  const config = parse(readFileSync(path, 'utf8')) ?? {};
  // Every URL comes from the config file; a missing entry is an error, not a silent localhost
  const origin = (entry, key) => {
    if (!entry?.url) {
      throw new Error(`${key}.url is missing from ${path}`);
    }
    return entry.port ? `${entry.url}:${entry.port}` : entry.url;
  };
  if (!config.frontend?.port) {
    throw new Error(`frontend.port is missing from ${path}`);
  }
  return {
    FRONTEND_PORT: config.frontend.port,
    FRONTEND_URL: origin(config.frontend, 'frontend'),
    AUTH_SERVICE_URL: origin(config.services?.auth, 'services.auth'),
    TRADE_API_URL: origin(config.services?.order, 'services.order'),
  };
}

function writeGenerated(urls) {
  const body = [
    '// GENERATED by scripts/sync-platform-config.mjs from Config/application.yaml. Do not edit.',
    '// Change the port in Config/application.yaml and run `npm start` (or `npm run sync-config`).',
    '',
    `export const PLATFORM_URLS = ${JSON.stringify(urls, null, 2).replace(/"([A-Z_]+)":/g, '$1:').replace(/"/g, "'")} as const;`,
    '',
  ].join('\n');
  if (!existsSync(outPath) || readFileSync(outPath, 'utf8') !== body) {
    writeFileSync(outPath, body);
  }
}

const isMain = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const urls = loadPlatformUrls();
  writeGenerated(urls);
  console.log(`platform config: auth=${urls.AUTH_SERVICE_URL} trade=${urls.TRADE_API_URL} ui-port=${urls.FRONTEND_PORT}`);

  const serveIndex = process.argv.indexOf('--serve');
  if (serveIndex !== -1) {
    const args = ['serve', '--port', String(urls.FRONTEND_PORT), ...process.argv.slice(serveIndex + 1)];
    const child = spawn('ng', args, { stdio: 'inherit', shell: true, cwd: appRoot });
    child.on('exit', (code) => process.exit(code ?? 0));
  }
}
